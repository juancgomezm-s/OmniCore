namespace OmniCore.Client;

/// <summary>French and Italian translations for the original shared runtime catalog.</summary>
public static class LegacyLocaleResources
{
    private static readonly IReadOnlyCollection<string> CatalogKeys =
        Localization.SpanishKeys.Distinct(StringComparer.Ordinal).ToArray();

    public static IReadOnlyCollection<string> Keys => CatalogKeys;
    public static bool ContainsKey(string key) => CatalogKeys.Contains(key, StringComparer.Ordinal);

    public static bool TryTranslate(string locale, string key, out string text)
    {
        text = "";
        if (locale is not ("fr" or "it")) return false;
        if ((locale == "fr" ? French : Italian).TryGetValue(key, out text!)) return true;
        return PolicyPreferencesResources.TryTranslate(locale, key, out text!)
            || SecurityPreferencesResources.TryTranslate(locale, key, out text!)
            || DiagnosticsPreferencesResources.TryTranslate(locale, key, out text!)
            || ShellUiResources.TryTranslate(locale, key, out text!)
            || SessionPreferencesResources.TryTranslate(locale, key, out text!)
            || AccountsPreferencesResources.TryTranslate(locale, key, out text!)
            || ClientCommandResources.TryTranslate(locale, key, out text!)
            || LocaleRuntimeResources.TryTranslate(locale, key, out text!)
            || PreferencesUiResources.TryTranslate(locale, key, out text!)
            || PreferenceCategoryCatalog.TryTranslate(locale, key, out text!);
    }

