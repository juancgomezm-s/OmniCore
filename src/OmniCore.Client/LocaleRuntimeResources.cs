    public static IReadOnlyCollection<string> Keys => Catalog["es"].Keys.ToArray();

    public static bool TryTranslate(string locale, string key, out string text)
    {
        if (Catalog.TryGetValue(locale, out var resources) && resources.TryGetValue(key, out text!))
            return true;
        text = string.Empty;
        return false;
    }
