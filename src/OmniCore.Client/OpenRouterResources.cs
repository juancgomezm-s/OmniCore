    private static readonly string[] Locales = ["es", "en", "fr", "it"];
    public static IReadOnlyCollection<string> Keys => Catalogs[0].Keys.ToArray();
    public static bool ContainsKey(string key) => Catalogs[0].ContainsKey(key);
    public static bool TryTranslate(string locale, string key, out string text)
    {
        var index = Array.IndexOf(Locales, UiLocaleCodes.NormalizeOrDefault(locale));
        if (index >= 0 && Catalogs[index].TryGetValue(key, out text!)) return true;
        text = string.Empty;
        return false;
    }
